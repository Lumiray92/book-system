    bi.bookCode  AS 图书编号,
    bt.typeName  AS 图书分类,
    bi.bookName  AS 图书名称,
    bi.bookAuthor AS 作者,
    bi.publishPress AS 出版社,
    DATE_FORMAT(bi.creationTime, '%Y-%m-%d') AS 入库时间,
    CASE bi.borrowed WHEN 1 THEN '已借阅' ELSE '未借阅' END AS 是否借阅
FROM book_info bi
         JOIN book_type bt ON bt.id = bi.bookType
ORDER BY bi.creationTime DESC
LIMIT 5;